import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
import {spawnSync} from 'node:child_process';
const root=fileURLToPath(new URL('..',import.meta.url));
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const manifest=JSON.parse(read('deployment/source-baseline.json'));
const settings=JSON.parse(read('deployment/observed-settings-2026-11-22.json'));
const source=fs.readFileSync(path.join(root,'worker.js'));
assert.equal(createHash('sha256').update(source).digest('hex'),manifest.source_sha256,'Active source differs from observed deployed baseline: review and update provenance before accepting a new baseline');
assert.equal(source.length,manifest.source_bytes);
assert.equal(settings.bindings.length,14);
assert.equal(settings.compatibility_date,'2026-10-01');
const byName=Object.fromEntries(settings.bindings.map(b=>[b.name,b]));
assert.equal(byName.TOKENS.namespace_id,'e8a0c8c2d28a41de916384984081917d');
assert.deepEqual(byName.MESA_STORE,{class_name:'MesaStore',name:'MESA_STORE',namespace_id:'e6e65d1561a84563a115add97010fc5a',type:'durable_object_namespace'});
assert.deepEqual(settings.bindings.filter(b=>b.type==='secret_text').map(b=>b.name).sort(),['APP_KEY','CMC_API_KEY','GOOGLE_CLIENT_ID','GOOGLE_CLIENT_SECRET','NOTION_TOKEN']);
assert(settings.bindings.filter(b=>b.type==='secret_text').every(b=>Object.keys(b).sort().join(',')==='name,type'),'Secret metadata must contain names and types only');
const config=read('wrangler.toml');
const main=config.match(/^main\s*=\s*"([^"]+)"/m)?.[1];
assert.equal(main,'DEPLOYMENT-BLOCKED-see-DEPLOYMENT.md.mjs');
assert.equal(fs.existsSync(path.join(root,main)),false,'Guard entrypoint must remain absent');
assert.match(config,/name = "MESA_STORE"\s+class_name = "MesaStore"/);
assert(!/^\[\[migrations\]\]/m.test(config),'Do not invent migration history');
assert.equal(manifest.migration_history_verified,false);
assert.equal(manifest.deployment_enabled,false);
const result=spawnSync(process.execPath,[path.join(root,'scripts/deploy-blocked.mjs')],{encoding:'utf8'});
assert.equal(result.status,1);
assert.match(result.stderr,/DEPLOYMENT BLOCKED/);
console.log('PASS source baseline, 14 binding identities, secret-name-only metadata, absent-input Wrangler guard, and local deploy guard. No external calls.');
